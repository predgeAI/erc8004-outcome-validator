#!/usr/bin/env node
// Regenerates src/core/mainnet-validator.ts from the mainnet run receipts in ../monad/mainnet/runs/.
// Later runs override earlier ones per market (a --respond run turns an open request into a verdict).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const RUNS = path.join(HERE, "..", "..", "monad", "mainnet", "runs");
const out = {};
let contract = null;
for (const f of readdirSync(RUNS).filter((n) => n.startsWith("live-") && n.endsWith(".json")).sort()) {
  const run = JSON.parse(readFileSync(path.join(RUNS, f), "utf8"));
  if (run.chainId !== 143) continue;
  contract = run.contract;
  for (const v of run.verdicts) {
    if (!v.request || v.request.status !== 1) continue;
    out[v.market_id] = {
      requestHash: v.requestHash,
      proposal: v.proposal,
      recordUrl: v.responseURI ?? v.requestURI,
      tx: (v.response ?? v.request).tx,
    };
  }
}
const body = `// Generated by scripts/gen-mainnet-verdicts.mjs from monad/mainnet/runs/*.json. Do not edit by hand.
export const MAINNET_VALIDATOR_CONTRACT = ${JSON.stringify(contract)};
export const MAINNET_VALIDATOR_VERDICTS: Readonly<Record<string, { requestHash: \`0x\${string}\`; proposal: string; recordUrl: string; tx: string }>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(path.join(HERE, "..", "src", "core", "mainnet-validator.ts"), body);
console.log(`${Object.keys(out).length} markets -> src/core/mainnet-validator.ts`);
